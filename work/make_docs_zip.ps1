param([string]$Stamp = (Get-Date -Format "yyyy-MM-dd_HHmmss"))
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location (Join-Path $Root "..")
$outDir = Join-Path (Get-Location) "work\archive"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
$stage = Join-Path (Get-Location) "work\archive_stage_$Stamp"
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force -Path $stage | Out-Null
$include = @("docs","spec","data","report","tests","server\data")
foreach ($rel in $include) {
    $src = Join-Path (Get-Location) $rel
    if (Test-Path $src) {
        $dst = Join-Path $stage $rel
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dst) | Out-Null
        Copy-Item -Recurse -Force $src $dst
    }
}
Get-ChildItem $stage -Recurse -File | Where-Object {
    $_.Extension -in ".png",".jpg",".jpeg",".webp",".gif",".apk",".zip",".db",".so",".dll",".exe"
} | Remove-Item -Force
$zip = Join-Path $outDir "TFTF_docs_$Stamp.zip"
Compress-Archive -Path (Join-Path $stage "*") -DestinationPath $zip -CompressionLevel Optimal
$hash = (Get-FileHash $zip -Algorithm SHA256).Hash.ToLower()
$size = (Get-Item $zip).Length
Remove-Item -Recurse -Force $stage
$integrity = @"
# Integrity (docs archive $Stamp)

- file: ``work/archive/TFTF_docs_$Stamp.zip``
- sha256: ``$hash``
- bytes: $size
- contents: docs, spec, data, report, tests (JSON/text only), server/data JSON
- excluded: APK, asset bundles, screenshots, SQLite DB, .git
- generated by: ``work/make_docs_zip.ps1``

The archive is outside git. It is not a full project backup and does not
include ODR/asset packs.
"@
Set-Content -Encoding utf8 (Join-Path (Get-Location) "docs\INTEGRITY.md") $integrity
Write-Host "zip: $zip"
Write-Host "sha256: $hash"
Write-Host "bytes: $size"
